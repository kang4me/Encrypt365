    private final UrlEntity urlEntity = new UrlEntity();
    private final String[] str = {"普通编码", "特殊符号编码", "一次全编/解"};
    private final String[] strSet = {"utf-8", "gb2312"};

    public urlUI(MontoyaApi api, Injector injector) {
        log = api.logging();
        history = injector.getInstance(History.class);
        historyEntity = injector.getInstance(HistoryEntity.class);
        urlEncrypt = injector.getInstance(UrlEncrypt.class);
        ini();

        encode.addActionListener((e) -> {
            setEntity();
            encodeSelect();
            urlDecode.setText(urlEntity.getOutputString());
            historyEntity.setUrlEntity(urlEntity);
            history.urlEncryptHistory(injector);
        });
        decode.addActionListener((e) -> {
            setEntity();
            urlEntity.setOutputString(urlEncrypt.urlDecode(urlEntity.getInputString(), Charset.forName(urlEntity.getCharSet())));
            urlDecode.setText(urlEntity.getOutputString());
            historyEntity.setUrlEntity(urlEntity);
            history.urlEncryptHistory(injector);
        });
    }

    private void encodeSelect() {
        switch (urlEntity.getModel()) {
            case "普通编码" ->
                    urlEntity.setOutputString(urlEncrypt.urlEncode(urlEntity.getInputString(), Charset.forName(urlEntity.getCharSet())));
            case "特殊符号编码" ->
                    urlEntity.setOutputString(urlEncrypt.urlEncodeAll(urlEntity.getInputString(), Charset.forName(urlEntity.getCharSet())));
            case "一次全编/解" ->
                    urlEntity.setOutputString(urlEncrypt.urlEncodeAlltoA_Z(urlEntity.getInputString(), Charset.forName(urlEntity.getCharSet())));
        }
    }


    private void ini() {
        for (String value : str) {
            model.addItem(value);
        }
        for (String value : strSet) {
            charSet.addItem(value);
        }
    }

    private void setEntity() {
        urlEntity.setInputString(urlEncode.getText());
        urlEntity.setModel(str[model.getSelectedIndex()]);
        urlEntity.setCharSet(strSet[charSet.getSelectedIndex()]);
    }

